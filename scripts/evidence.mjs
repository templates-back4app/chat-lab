// File: scripts/evidence.mjs · Node 22 ESM
// Turns the rows the test suites append to docs/evidence/.rows-<target>.jsonl into the evidence file:
//   docs/evidence/subscription-matrix-<target>-<date>.md   (one row per test: persona, attempt, HTTP/Parse
//                                                           code or ws frames, body assertion, state assertion)
// Wired into npm: `pretest` runs `--reset` (start a fresh collection), `posttest` writes the file, so the
// committed evidence always reflects ONE complete `npm test` run. Run dates use the local machine's date.
import { readFileSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { ROOT, args } from './lib/env.mjs';

const EVIDENCE_DIR = path.join(ROOT, 'docs', 'evidence');
// Same target labeling as test/helpers.mjs: evidence is labeled by what it actually ran against.
const TARGET = !process.env.TEST_SERVER_URL ? 'local'
  : /back4app\.com/.test(process.env.TEST_SERVER_URL) ? 'back4app' : 'remote-rehearsal';
const ROWS_FILE = path.join(EVIDENCE_DIR, `.rows-${TARGET}.jsonl`);
const a = args();

if (a.reset) {
  rmSync(ROWS_FILE, { force: true });
  process.exit(0);
}

if (!existsSync(ROWS_FILE)) {
  console.error(`evidence: no .rows-${TARGET}.jsonl — run \`npm test\` first.`);
  process.exit(1);
}

const rows = readFileSync(ROWS_FILE, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
// One row per id: the LAST record of a run wins (re-runs within one `npm test` overwrite).
const byId = new Map();
for (const r of rows) byId.set(r.id, r);
const date = new Date().toISOString().slice(0, 10);

const order = (id) => {
  const m = id.match(/^([A-Z]+)(\d+)(.*)$/);
  const series = { P: 0, T: 1, G: 2, R: 3, M: 4, H: 5 }[m ? m[1] : 'Z'] ?? 9;
  return [series, m ? Number(m[2]) : 999, m ? m[3] : ''];
};
const sorted = [...byId.values()].sort((x, y) => {
  const [a1, a2, a3] = order(x.id); const [b1, b2, b3] = order(y.id);
  return a1 - b1 || a2 - b2 || (a3 < b3 ? -1 : a3 > b3 ? 1 : 0);
});

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (list) => [
  '| # | Persona | Attempt | HTTP / code / frames | Body assertion | State assertion |',
  '|---|---|---|---|---|---|',
  ...list.map((r) => `| ${r.id} | ${esc(r.persona)} | ${esc(r.attempt)} | ${esc(r.status)} · ${esc(r.code)} | ${esc(r.body)} | ${esc(r.state)} |`),
].join('\n');

const header = (title) => TARGET === 'local' ? `# ${title} — LOCAL run, ${date}

Generated by \`npm test\` (scripts/evidence.mjs) from a single complete run against an in-process
parse-server (PostgreSQL adapter, port 5433, database \`chat_test\`) with LiveQuery enabled for \`Message\`.
**Local evidence only** — the Back4app run of the same suites is the live phase and produces its own file;
local and live results are compared in \`local-vs-live.md\` (live phase). Every assertion checks the response
body AND the database state (master-key read-back) — and, for subscription rows, the exact frames received —
not just the status code.
` : `# ${title} — ${TARGET.toUpperCase()} run, ${date}

Generated by \`TEST_SERVER_URL=… npm test\` (scripts/evidence.mjs) from a single complete run against
${TARGET === 'back4app' ? 'the Back4app backend' : 'a non-production rehearsal target'} with the App ID + REST/JS key + the administrative
setup token only — state read-backs went through the gated Cloud function testInspect, never the master key.
Rows marked "skipped"/"local-only" need master-key or direct-database access and are recorded in the LOCAL
evidence file instead. Every other assertion checks the response body AND the database state, not just the
status code.
`;

writeFileSync(path.join(EVIDENCE_DIR, `subscription-matrix-${TARGET}-${date}.md`), `${header('Subscription + write-path test matrix')}
${table(sorted)}

## Live-only measurements (not quoted from local runs, by design)

| What | Why live-only |
|---|---|
| M0–M6 headline numbers on Back4app | the published numbers must come from the platform the article is about; the local run proves mechanics and produces loopback files clearly labeled local |
| T8 revocation delay distribution (10 runs, measure-revocation.mjs) | loopback timing is meaningless for the claim; the local T8 row above records the mechanism (LiveQuery auth cache) |
| M5 throttle ceiling | the local parse-server has no platform throttle; Parse code 155 only exists on the live plan |

Suites in this run: ${[...new Set(sorted.map((r) => r.suite))].join(', ')} · ${sorted.length} matrix rows recorded at ${new Date().toISOString()}.
`);

console.log(`evidence: wrote subscription-matrix-${TARGET}-${date}.md (${sorted.length} rows)`);
// Stale evidence from earlier dates is left in place deliberately (dated files are the house style);
// list what exists so a stale file is noticed:
for (const f of readdirSync(EVIDENCE_DIR).filter((f) => !f.startsWith('.')).sort()) console.log(`  docs/evidence/${f}`);
